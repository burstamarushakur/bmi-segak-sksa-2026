-- BMI / SEGAK SKSA — isolated storage inside the existing Portal Koku Supabase project.
-- This migration creates ONLY segak_* objects. It does NOT ALTER Portal Koku tables.

create extension if not exists pgcrypto;

create table if not exists public.segak_student_profiles (
  student_id uuid primary key,
  full_name_cache text not null default '',
  gender text null check (gender is null or gender in ('LELAKI','PEREMPUAN')),
  mykid text null,
  guardian_phone text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.segak_records (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null,
  session_year integer not null check (session_year between 2000 and 2100),
  class_id uuid null,
  class_code text not null,
  class_name text not null default '',
  year_level integer not null check (year_level between 1 and 6),
  pengisian smallint not null check (pengisian in (1,2)),
  age smallint null check (age is null or age between 5 and 19),
  height_cm numeric(5,1) null check (height_cm is null or height_cm between 50 and 250),
  weight_kg numeric(5,1) null check (weight_kg is null or weight_kg between 5 and 250),
  bmi numeric(5,1) null,
  bmi_status text null,
  step_pulse integer null check (step_pulse is null or step_pulse between 20 and 300),
  push_ups integer null check (push_ups is null or push_ups between 0 and 200),
  curl_ups integer null check (curl_ups is null or curl_ups between 0 and 25),
  sit_reach_cm integer null check (sit_reach_cm is null or sit_reach_cm between 0 and 100),
  total_score smallint null check (total_score is null or total_score between 4 and 20),
  grade text null check (grade is null or grade in ('A','B','C','D','E','F')),
  fitness_status text null,
  test_date date null,
  source text not null default 'webapp' check (source in ('webapp','legacy_sheet')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint segak_records_student_session_term_unique unique (student_id, session_year, pengisian)
);

create table if not exists public.segak_legacy_staging (
  id uuid primary key default gen_random_uuid(),
  session_year integer not null,
  class_code text not null,
  full_name text not null,
  normalized_name text not null,
  gender text null check (gender is null or gender in ('LELAKI','PEREMPUAN')),
  pengisian smallint not null default 1 check (pengisian in (1,2)),
  age smallint null,
  height_cm numeric(5,1) null,
  weight_kg numeric(5,1) null,
  step_pulse integer null,
  push_ups integer null,
  curl_ups integer null,
  sit_reach_cm integer null,
  test_date date null,
  migrated_student_id uuid null,
  migrated_at timestamptz null,
  created_at timestamptz not null default now(),
  constraint segak_legacy_staging_unique unique (session_year, class_code, normalized_name, pengisian)
);

create table if not exists public.segak_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.segak_audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  session_year integer null,
  class_code text null,
  student_id uuid null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

