create index if not exists idx_segak_legacy_unmigrated
  on public.segak_legacy_staging(session_year,class_code)
  where migrated_student_id is null;
create index if not exists idx_segak_records_session_class_term
  on public.segak_records(session_year,class_code,pengisian);
create index if not exists idx_segak_records_student
  on public.segak_records(student_id);
create index if not exists idx_segak_records_year_level
  on public.segak_records(session_year,year_level);
create index if not exists idx_segak_audit_created_at
  on public.segak_audit_log(created_at desc);

create or replace function public.set_segak_updated_at()
returns trigger
language plpgsql
set search_path=public
as $$
begin
  new.updated_at=now();
  return new;
end;
$$;

drop trigger if exists trg_segak_profiles_updated_at on public.segak_student_profiles;
create trigger trg_segak_profiles_updated_at before update on public.segak_student_profiles
for each row execute function public.set_segak_updated_at();

drop trigger if exists trg_segak_records_updated_at on public.segak_records;
create trigger trg_segak_records_updated_at before update on public.segak_records
for each row execute function public.set_segak_updated_at();

drop trigger if exists trg_segak_settings_updated_at on public.segak_settings;
create trigger trg_segak_settings_updated_at before update on public.segak_settings
for each row execute function public.set_segak_updated_at();

